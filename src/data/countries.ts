/** Emoji flag from an ISO 3166-1 alpha-2 code. */
export function flagEmoji(iso2: string): string {
  return iso2
    .toUpperCase()
    .replace(/[A-Z]/g, (c) => String.fromCodePoint(0x1f1e6 + c.charCodeAt(0) - 65));
}
